// The offices of the gods (plan track G): for each planetary god the field carries, every join that gives it an office —
// the signs it rules, the sephira it stands at, the Atu and the small cards it governs, its element, its stage of the opus —
// read straight from field.json's joins, with each join's basis and voice. A report, not a source: nothing here is typed.
//   node scripts/offices.mjs [--field <field.json>] [--out <file>]   (default: ProjectCentral/docs/OFFICES-OF-THE-GODS.md)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const fieldFile = arg('--field', path.join(ROOT, 'public', 'data', 'field.json'));
const outFile = arg('--out', path.join(ROOT, 'ProjectCentral', 'docs', 'OFFICES-OF-THE-GODS.md'));

/** The planetary god families, in the order of the classical seven. */
export const GODS = ['sun', 'moon', 'mercurius', 'venus', 'mars', 'jupiter', 'saturn'];
const SIGNS = new Set(['aries', 'taurus', 'gemini', 'cancer', 'leo', 'virgo', 'libra', 'scorpio', 'sagittarius', 'capricorn', 'aquarius', 'pisces']);
const SEPHIROTH = new Set(['kether', 'chokmah', 'binah', 'chesed', 'geburah', 'tiphareth', 'netzach', 'hod', 'yesod', 'malkuth']);
const ELEMENTS = new Set(['fire', 'water', 'air', 'earth-element']);
const STAGES = new Set(['nigredo', 'albedo', 'citrinitas', 'rubedo']);

export function officesOf(field) {
  const fam = new Map(field.families.map((f) => [f.id, f]));
  const name = (t, id) => (t === 'family' ? fam.get(id)?.name : t === 'archetype' ? field.archetypes.find((a) => a.id === id)?.name : field.theoretics.find((x) => x.id === id)?.name) ?? id;
  const out = {};
  for (const god of GODS) {
    const rows = { signs: [], sephiroth: [], atu: [], cards: [], decans: [], elements: [], stages: [], other: [] };
    for (const j of field.joins ?? []) {
      let other;
      if (j.a.type === 'family' && j.a.id === god) other = j.b;
      else if (j.b.type === 'family' && j.b.id === god) other = j.a;
      else continue;
      const row = { id: other.id, name: name(other.type, other.id), type: other.type, basis: j.basis, system: j.system ?? '', voice: j.voice ?? '', note: j.note };
      if (other.type !== 'family') rows.other.push(row);
      else if (SIGNS.has(other.id)) rows.signs.push(row);
      else if (SEPHIROTH.has(other.id)) rows.sephiroth.push(row);
      else if (/^thoth-(ace|two|three|four|five|six|seven|eight|nine|ten)-of-/.test(other.id)) rows.cards.push(row);
      else if (/^thoth-/.test(other.id) && !/-of-|arcana|tarot|^thoth-(wands|cups|swords|disks)$/.test(other.id)) rows.atu.push(row);
      else if (other.id.startsWith('decan-')) rows.decans.push(row);
      else if (ELEMENTS.has(other.id)) rows.elements.push(row);
      else if (STAGES.has(other.id)) rows.stages.push(row);
      else rows.other.push(row);
    }
    out[god] = { name: fam.get(god)?.name ?? god, rows };
  }
  return out;
}

export function renderOffices(field) {
  const o = officesOf(field);
  const L = [];
  L.push('# Offices of the gods', '',
    'Generated by `node scripts/offices.mjs` from the field\'s joins (`public/data/field.json` → `joins`). A report, not a source: every row is a join in `curation/joins.json` with its own basis and voice. Basis `jung` = Jung states it; `inferred` = follows from his usage; `site` = a reading made here or another voice\'s attribution (Crowley, Burt, a Latin text quoted by Jung), named in the voice column. Where a god has no row for an office the sources give none — nothing is filled in.',
    '', `Planets are the field's god-figure families; the sky layer ties the planets Venus and Mercury to \`venus\` and \`mercurius\`. Uranus, Neptune and Pluto have no family and no row.`, '');
  const sections = [['signs', 'Signs it rules'], ['sephiroth', 'Sephira'], ['atu', 'Atu of the Thoth deck'], ['cards', 'Small cards'], ['decans', 'Decans'], ['elements', 'Element'], ['stages', 'Stage of the opus'], ['other', 'Other joins']];
  for (const god of GODS) {
    const g = o[god];
    const total = Object.values(g.rows).reduce((n, r) => n + r.length, 0);
    L.push(`## ${g.name}`, '', `\`${god}\` · ${total} joins`, '');
    for (const [k, title] of sections) {
      const rows = g.rows[k];
      if (!rows.length) continue;
      L.push(`**${title}**`, '');
      for (const r of rows.sort((a, b) => a.name.localeCompare(b.name))) L.push(`- ${r.name} · ${r.basis}${r.voice ? ` · ${r.voice}` : ''} — ${r.note}`);
      L.push('');
    }
    if (!total) L.push('_No joins in the field._', '');
  }
  return L.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const field = JSON.parse(fs.readFileSync(fieldFile, 'utf8'));
  fs.writeFileSync(outFile, renderOffices(field) + '\n');
  const o = officesOf(field);
  for (const g of GODS) console.log(`${g}: ${Object.values(o[g].rows).reduce((n, r) => n + r.length, 0)} joins`);
  console.log(`wrote ${path.relative(ROOT, outFile)}`);
}
